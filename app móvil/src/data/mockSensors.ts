/** Genera un detalle genérico para sensores sin ficha propia en el mock. */
export function buildDetailFromSensor(s: Sensor): SensorDetail {
  const base = mockSensorDetail['SENS-SOIL-02'];
  const isTemp = s.unit === '°C';
  return {
    ...base,
    id: s.id,
    module: s.location.toUpperCase(),
    title: s.name,
    icon: s.icon,
    value: s.value,
    unit: s.unit,
    status: s.status,
    statusLabel: s.status === 'normal' ? 'En rango' : 'Atención preventiva',
    history: {
      ...base.history,
      title: `Histórico · ${s.name}`,
      unit: s.unit,
      points: s.trend.map((v, i) => ({ label: `${String(i * 2).padStart(2, '0')}:00`, value: v })),
      comfortMin: isTemp ? 20 : base.history.comfortMin,
      comfortMax: isTemp ? 26 : base.history.comfortMax,
      threshold: isTemp ? 20 : base.history.threshold,
    },
    thresholdEditor: {
      ...base.thresholdEditor,
      subtitle: s.name,
      unit: s.unit,
      scaleMin: isTemp ? 10 : 0,
      scaleMax: isTemp ? 40 : 100,
      min: isTemp ? 20 : 65,
      max: isTemp ? 26 : 85,
      step: isTemp ? 0.5 : 1,
      automations: isTemp
        ? [
            { id: 'fan', icon: 'fan', title: 'Extractores automáticos', description: 'Activar si supera los 26.5 °C' },
            { id: 'push', icon: 'bell-ring-outline', title: 'Alerta push telefónica', description: 'Notificar si temperatura < 18.0 °C' },
          ]
        : base.thresholdEditor.automations,
    },
  };
}
